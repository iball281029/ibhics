def defaults():
    return {
        key: {field: event[field] for field in ("in_app", "email", "level")}
        for key, event in CATALOG.items()
    }


def publish(owner, event_id, message, key, **kwargs):
    """Managers can run independently without a notification service."""
    callback = getattr(owner, "event", None)
    if callback:
        return callback(event_id, message, key, **kwargs)


def legacy_id(level, category, message):
    """Bridge existing protection callbacks while preserving their public signature."""
    if category == "backup":
        return "backup.recovered" if level == "info" else "backup.failed"
    if category == "node":
        return "node.online" if level == "info" else "node.offline"
    if category == "quorum":
        return "quorum.restored" if level == "info" else "quorum.lost"
    return {
        "verify": "backup.verify_failed",
        "anomaly": "backup.anomaly",
        "rpo": "backup.rpo_breach",
        "capacity": "storage.low_space",
        "replication": "replication.failed",
        "subscription": "subscription.expiring",
    }.get(category)
